"""Builds the animated Android 12+ splash icon (AnimatedVectorDrawable) of
the MesMots logo: two letter tiles (M, m) and a star, drawn in the 1024px
space of assets/icon/icon_foreground.png. Letters come from Fredoka Bold.

usage: python3 tool/make_splash_avd.py assets/fonts/Fredoka-Bold.ttf \
    android/app/src/main/res/drawable/splash_animated.xml
(needs fontTools: pip install fonttools)
"""
import math
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

font_path, out_path = sys.argv[1:3]
font = TTFont(font_path)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()

# Logo layout, measured on the 1024px icon.
TILE = 330          # tile side
RADIUS = 62         # tile corner radius
SHADOW = 28         # 3D shadow offset
TILES = [
    # letter, center, angle, face, shadow, letter height
    ('M', (326, 544), -8, '#FFA726', '#E69500', 220),
    ('m', (690, 544), 8, '#FF7B9C', '#E66384', 150),
]
STAR_CENTER = (512, 255)
STAR_OUTER, STAR_INNER = 96, 42
STAR, STAR_SHADOW = '#FFD600', '#E6B400'

# Viewport: the splash shows a circle of 1/3 of the icon size, so the logo
# (half diagonal ~480) must fit a radius of viewport / 3.
VIEWPORT = 1480
CONTENT_CENTER = (512, 467)
SHIFT = (VIEWPORT / 2 - CONTENT_CENTER[0], VIEWPORT / 2 - CONTENT_CENTER[1])


def rounded_square(cx, cy, a, r, dy=0):
    x, y = cx - a / 2, cy - a / 2 + dy
    s = a - 2 * r
    return (f'M{x + r:.1f},{y:.1f} h{s:.1f} a{r},{r} 0 0 1 {r},{r} '
            f'v{s:.1f} a{r},{r} 0 0 1 -{r},{r} h-{s:.1f} '
            f'a{r},{r} 0 0 1 -{r},-{r} v-{s:.1f} a{r},{r} 0 0 1 {r},-{r} Z')


def glyph_path(char, cx, cy, height):
    """Glyph outline centered on (cx, cy), scaled to [height], y down."""
    glyph = glyphs[cmap[ord(char)]]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    k = height / (y1 - y0)
    pen = SVGPathPen(glyphs)
    # Flip y (font units go up) and center the box on (cx, cy).
    transform = (k, 0, 0, -k, cx - k * (x0 + x1) / 2, cy + k * (y0 + y1) / 2)
    glyph.draw(TransformPen(pen, transform))
    return pen.getCommands()


def star_path(cx, cy, outer, inner, dy=0):
    points = []
    for i in range(10):
        r = outer if i % 2 == 0 else inner
        angle = -math.pi / 2 + i * math.pi / 5
        points.append((cx + r * math.cos(angle), cy + dy + r * math.sin(angle)))
    return 'M' + ' L'.join(f'{x:.1f},{y:.1f}' for x, y in points) + ' Z'


def tile_group(i, letter, center, angle, face, shadow, height):
    cx, cy = center
    return f'''
        <group android:name="tile{i}" android:pivotX="{cx}" android:pivotY="{cy}"
            android:rotation="{angle}" android:scaleX="0" android:scaleY="0">
          <path android:fillColor="{shadow}"
              android:pathData="{rounded_square(cx, cy, TILE, RADIUS, SHADOW)}" />
          <path android:fillColor="{face}"
              android:pathData="{rounded_square(cx, cy, TILE, RADIUS)}" />
          <path android:fillColor="#FFFFFF"
              android:pathData="{glyph_path(letter, cx, cy, height)}" />
        </group>'''


def pop(target, delay):
    return f'''
  <target android:name="{target}">
    <aapt:attr name="android:animation">
      <set>
        <objectAnimator android:propertyName="scaleX" android:valueFrom="0"
            android:valueTo="1" android:startOffset="{delay}" android:duration="420"
            android:interpolator="@android:interpolator/overshoot" />
        <objectAnimator android:propertyName="scaleY" android:valueFrom="0"
            android:valueTo="1" android:startOffset="{delay}" android:duration="420"
            android:interpolator="@android:interpolator/overshoot" />
      </set>
    </aapt:attr>
  </target>'''


sx, sy = STAR_CENTER
xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by make_splash_avd.py: animated MesMots logo of the Android 12+
     splash. The tiles pop in one after the other, then the star drops on
     them. Under 1 s, the longest the system splash allows. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
  <aapt:attr name="android:drawable">
    <vector android:width="288dp" android:height="288dp"
        android:viewportWidth="{VIEWPORT}" android:viewportHeight="{VIEWPORT}">
      <group android:translateX="{SHIFT[0]:.1f}" android:translateY="{SHIFT[1]:.1f}">
{''.join(tile_group(i, *t) for i, t in enumerate(TILES))}
        <group android:name="star" android:pivotX="{sx}" android:pivotY="{sy}"
            android:translateY="-700" android:rotation="-144">
          <path android:fillColor="{STAR_SHADOW}"
              android:pathData="{star_path(sx, sy, STAR_OUTER, STAR_INNER, 12)}" />
          <path android:fillColor="{STAR}"
              android:pathData="{star_path(sx, sy, STAR_OUTER, STAR_INNER)}" />
        </group>
      </group>
    </vector>
  </aapt:attr>
{pop('tile0', 0)}
{pop('tile1', 160)}
  <target android:name="star">
    <aapt:attr name="android:animation">
      <set>
        <objectAnimator android:propertyName="translateY" android:valueFrom="-700"
            android:valueTo="0" android:startOffset="420" android:duration="520"
            android:interpolator="@android:anim/bounce_interpolator" />
        <objectAnimator android:propertyName="rotation" android:valueFrom="-144"
            android:valueTo="0" android:startOffset="420" android:duration="420"
            android:interpolator="@android:interpolator/decelerate_cubic" />
      </set>
    </aapt:attr>
  </target>
</animated-vector>
'''
open(out_path, 'w').write(xml)
print('written', out_path, len(xml), 'bytes')
